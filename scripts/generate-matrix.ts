import { writeFileSync } from "node:fs";
import { presetModes, presetPixels, encodePixels } from "../shared/matrix.js";
import { glyphs } from "../shared/matrix-font.js";

export function generatedMatrixHeader() {
  const font = Array.from(
    { length: 95 },
    (_, i) => glyphs[String.fromCharCode(i + 32).toUpperCase()] ?? glyphs["?"],
  );
  return `// Generated by scripts/generate-matrix.ts. Edit shared/matrix.ts or matrix-font.ts.
#pragma once
#include <stdint.h>
#include <string.h>
#include "heartbeat.h"
namespace MatrixProgram {
static const char* const names[] = {${presetModes.map((m) => JSON.stringify(m)).join(",")}};
static const uint8_t font[95][7] = {${font.map((g) => `{${g.join(",")}}`).join(",")}};
static const uint32_t presets[${presetModes.length}][64][3] = {
${presetModes
  .map(
    (m) =>
      `{ // ${m}\n${Array.from(
        { length: 64 },
        (_, i) =>
          `{${encodePixels(presetPixels(m, i))
            .match(/.{8}/g)!
            .map((w) => `0x${w}UL`)
            .join(",")}}`,
      ).join(",\n")}\n}`,
  )
  .join(",\n")}
};
inline int presetIndex(const char* mode) {
  for (unsigned i=0; i<sizeof(names)/sizeof(names[0]); ++i) if(!strcmp(mode,names[i])) return i;
  return -1;
}
inline int hex(char c) { return c<='9'?c-'0':(c>='a'?c-'a'+10:c-'A'+10); }
inline uint16_t build(const char* mode, uint8_t speed, const char* text, const char* const* custom, uint8_t customCount, uint32_t frames[][4]) {
  if(!strcmp(mode,"heart")) { Heartbeat::sequence(frames,speed); return 6; }
  const bool isText=!strcmp(mode,"text"),isCustom=!strcmp(mode,"custom"),off=!strcmp(mode,"off");
  const int preset=presetIndex(mode);
  if(!isText&&!isCustom&&!off&&preset<0) return 0;
  const unsigned length=strlen(text);
  const uint16_t count=isText?(length+3)*6+12:(isCustom?customCount:(off?1:64));
  const uint32_t duration=isText||isCustom?320-speed*25:160-speed*12;
  for(uint16_t f=0;f<count;f++) {
    for(int w=0;w<3;w++) frames[f][w]=0;
    if(preset>=0) for(int w=0;w<3;w++) frames[f][w]=presets[preset][f][w];
    else if(isCustom) for(int i=0;i<24;i++) frames[f][i/8]=(frames[f][i/8]<<4)|hex(custom[f][i]);
    else if(isText) {
      const int shift=(int)f-12;
      for(int y=0;y<7;y++) for(int x=0;x<12;x++) {
        const int at=x+shift;
        if(at<0 || at>=(int)length*6 || at%6==5)continue;
        const unsigned char c=text[at/6];
        if(c>=32&&c<=126&&((font[c-32][y]>>(4-at%6))&1)) {
          const int i=y*12+x;
          frames[f][i/32]|=1UL<<(31-i%32);
        }
      }
    }
    frames[f][3]=duration;
  }
  return count;
}
}
`;
}
if (process.argv[1]?.endsWith("generate-matrix.ts"))
  writeFileSync("firmware/mystery_box/matrix_program.h", generatedMatrixHeader());
